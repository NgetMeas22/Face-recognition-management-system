"""Declarative base, naming conventions and shared column mixins (PostgreSQL)."""

from datetime import datetime

from sqlalchemy import BigInteger, Enum, Identity, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.db.types import UTCDateTime, utcnow

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# Foreign keys referencing an IdMixin primary key use this type.
BigId = BigInteger


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class IdMixin:
    # GENERATED BY DEFAULT AS IDENTITY (SQL standard; preferred over SERIAL in PostgreSQL 10+).
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True, sort_order=-100)


class CreatedAtMixin:
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, server_default=func.now(), sort_order=100)


class TimestampMixin(CreatedAtMixin):
    updated_at: Mapped[datetime] = mapped_column(
        UTCDateTime, default=utcnow, onupdate=utcnow, server_default=func.now(), sort_order=100
    )


def enum_column(enum_cls: type, name: str, length: int = 20):
    """VARCHAR + CHECK instead of a native PostgreSQL ENUM type.

    Native enums can't drop values and need separate CREATE/DROP TYPE steps in migrations; a CHECK
    constraint (named ck_<table>_<name>) gives the same integrity and is easy to change later.
    """
    return Enum(
        enum_cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=length,
        values_callable=lambda members: [m.value for m in members],
        validate_strings=True,
    )
